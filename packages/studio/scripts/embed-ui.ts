/**
 * Reads the Vite build output and generates a TypeScript module
 * that exports the assets as strings, ready for the middleware to serve.
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const distDir = resolve(import.meta.dirname, "../dist-ui");
const outFile = resolve(import.meta.dirname, "../src/ui-assets.ts");

// Read all files from dist-ui
const files = new Map<string, { content: string; contentType: string }>();

function walk(dir: string, prefix: string) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const fullPath = join(dir, entry.name);
    const relativePath = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      walk(fullPath, relativePath);
    } else {
      const content = readFileSync(fullPath);
      const ext = entry.name.split(".").pop() ?? "";
      const contentType =
        ext === "html"
          ? "text/html"
          : ext === "css"
            ? "text/css"
            : ext === "js"
              ? "application/javascript"
              : "application/octet-stream";

      files.set(`/${relativePath}`, {
        content: content.toString("base64"),
        contentType,
      });
    }
  }
}

walk(distDir, "");

// Generate the module
const entries = [...files.entries()]
  .map(([path, { content, contentType }]) => `  ["${path}", { content: "${content}", contentType: "${contentType}" }]`)
  .join(",\n");

const code = `// biome-ignore-all format: auto-generated file with base64 assets
// Auto-generated by scripts/embed-ui.ts — do not edit manually.

interface Asset {
  content: string;  // base64-encoded
  contentType: string;
}

const assets = new Map<string, Asset>([
${entries},
]);

export function getAsset(path: string): { body: Uint8Array; contentType: string } | null {
  // Try exact match
  let asset = assets.get(path);
  if (asset) {
    return { body: Uint8Array.from(atob(asset.content), (c) => c.charCodeAt(0)), contentType: asset.contentType };
  }
  // SPA fallback — serve index.html for non-asset paths
  if (!path.includes(".")) {
    asset = assets.get("/index.html");
    if (asset) {
      return { body: Uint8Array.from(atob(asset.content), (c) => c.charCodeAt(0)), contentType: asset.contentType };
    }
  }
  return null;
}
`;

writeFileSync(outFile, code);
console.log(`Embedded ${files.size} assets into ${outFile}`);
